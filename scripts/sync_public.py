"""Project the approved Aoi surface into a separate public checkout.

The destination is deliberately treated as a managed file set.  The tool
never walks or deletes the destination recursively: files are copied only
from the allow-list below, stale files are removed only when their previous
manifest hash still matches, and ``.git`` plus all unlisted files are left
alone.  A release run should use ``--source-ref`` and pass a runtime package
generated by ``scripts/package_runtime.py --source-ref`` from the same
source commit.

Examples (PowerShell)::

    python scripts/sync_public.py --dry-run
    python scripts/sync_public.py --runtime-package .local/runtime-public \
        --model-package artifacts/models/kotonoha-aoi.zip --source-ref <SHA>

The source repository remains the canonical production repository.  This
script creates a projection; it does not create or push a GitHub repository.
Writes are per-file atomic after the complete preflight. An unexpected
process interruption during apply can leave a partial managed set; rerun
after resolving the reported error. Unmanaged files and ``.git`` are never
part of that apply set.
"""
