class SyncError(RuntimeError):
    """A verified input, path, or destination conflict blocks synchronization."""


@dataclass(frozen=True)
class Entry:
    path: str
    source_path: str
    data: bytes
    source_sha256: str
    transform: str | None = None

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.data).hexdigest()


def clean_path(value: str | Path) -> str:
    """Return a slash-separated relative path and reject traversal."""
    raw = str(value).replace("\\", "/")
    path = Path(raw)
    if path.is_absolute() or any(part in ("", ".", "..") for part in path.parts):
        raise SyncError(f"unsafe relative path: {value}")
    if any(part.casefold() == ".git" for part in path.parts):
        raise SyncError(f"protected .git path: {value}")
    if path.as_posix().casefold() == MANIFEST_NAME.casefold():
        raise SyncError(f"reserved public manifest path: {value}")
    return "/".join(path.parts)


def is_reparse(path: Path) -> bool:
    """Detect symlinks and Windows reparse points, including dangling links."""
    try:
        info = os.lstat(path)
    except FileNotFoundError:
        return os.path.lexists(path)
    attrs = getattr(info, "st_file_attributes", 0)
    return stat.S_ISLNK(info.st_mode) or bool(attrs & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400))


def reject_reparse_chain(path: Path, label: str) -> Path:
    """Resolve a path only after checking every existing ancestor component."""
    absolute = Path(os.path.abspath(path))
    current = Path(absolute.anchor)
    for part in absolute.parts[1:]:
        current = current / part
        if is_reparse(current):
            raise SyncError(f"{label} contains a symlink/junction/reparse point: {current}")
    return absolute


def ensure_directory(path: Path, label: str) -> Path:
    """Resolve a directory without following an existing symlink/reparse root."""
    absolute = reject_reparse_chain(path, label)
    if absolute.exists() and not absolute.is_dir():
        raise SyncError(f"{label} must be a directory: {absolute}")
    return absolute


def inside(root: Path, child: Path, label: str = "path") -> Path:
    root = root.resolve(strict=False)
    child = child.resolve(strict=False)
    try:
        child.relative_to(root)
    except ValueError as exc:
        raise SyncError(f"{label} escapes its root: {child}") from exc
    return child


def reject_reparse_parents(root: Path, relative: str) -> Path:
    """Resolve a destination target while refusing symlinked path components."""
    target = root
    parts = Path(relative).parts
    for part in parts[:-1]:
        target = target / part
        if is_reparse(target):
            raise SyncError(f"destination path component is a symlink/junction: {target}")
        if target.exists() and not target.is_dir():
            raise SyncError(f"destination path component is a regular file: {target}")
    target = target / parts[-1]
    if is_reparse(target):
        raise SyncError(f"destination target is a symlink/junction: {target}")
    return inside(root, target, "destination path")


def run_git(source: Path, *args: str) -> bytes:
    try:
        return subprocess.check_output(
            ["git", "-C", str(source), *args],
            stderr=subprocess.PIPE,
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        detail = getattr(exc, "stderr", b"")
        message = detail.decode("utf-8", "replace").strip() if detail else str(exc)
        raise SyncError(f"git command failed: {message}") from exc


def source_commit(source: Path, source_ref: str | None) -> str:
    ref = source_ref or "HEAD"
    raw = run_git(source, "rev-parse", "--verify", ref + "^{commit}").decode("ascii", "strict").strip()
    if not re.fullmatch(r"[0-9a-f]{40}", raw):
        raise SyncError(f"source ref did not resolve to a full commit: {ref}")
    return raw


def tracked_paths(source: Path, source_ref: str | None) -> set[str]:
    if source_ref:
        raw = run_git(source, "ls-tree", "-r", "--name-only", source_ref)
    else:
        raw = run_git(source, "ls-files", "-z")
    if source_ref:
        rows = raw.decode("utf-8").splitlines()
    else:
        rows = raw.decode("utf-8").split("\0")
    return {clean_path(row) for row in rows if row}


def source_status(source: Path) -> bool:
    raw = run_git(source, "status", "--porcelain=v1", "--untracked-files=all")
    return bool(raw.strip())


def read_source(source: Path, relative: str, source_ref: str | None, tracked: set[str]) -> bytes:
    if source_ref and relative in tracked:
        return run_git(source, "show", f"{source_ref}:{relative}")
    if source_ref and relative not in tracked:
        raise SyncError(
            f"{relative} is not present in source ref {source_ref}; "
            "commit the public input before a release sync"
        )
    path = inside(source, source / Path(relative), "source path")
    reject_reparse_chain(path, "source path")
    if not path.exists() or not path.is_file() or is_reparse(path):
        raise SyncError(f"source file is missing or unsafe: {path}")
    return path.read_bytes()


def public_source_path(relative: str) -> bool:
    """Return whether a tracked source path belongs in the public projection."""
    if relative in TOP_LEVEL or relative in PUBLIC_DOCS or relative in PUBLIC_WEB_FILES:
        return True
    if relative in PUBLIC_EXTRAS:
        return True
    if relative.startswith("seethrough_rig/"):
        return True
    if relative.startswith("scripts/"):
        return True
    if relative.startswith("tests/"):
        return True
    if relative.startswith("web/js/") or relative.startswith("web/css/"):
        return True
    if relative.startswith("web/motions/"):
        return True
    if relative.startswith("web/models/aoi/"):
        return True
    if relative.startswith("recipes/"):
        return Path(relative).name in PUBLIC_RECIPE_NAMES
    # Source artwork and all historical candidate/reference material stay out
    # of the public repository.  The baked model above is the redistribution
    # surface for the adopted character.
    return False


def transform_text(relative: str, data: bytes) -> tuple[bytes, str | None]:
    if Path(relative).suffix.lower() not in TEXT_SUFFIXES:
        return data, None
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return data, None
    original = text
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # Location strings are meaningful in Python defaults and are only
    # redacted in prose.  The public projection must not turn executable
    # source into a literal ``${...}`` path.
    if Path(relative).suffix.lower() in {".md", ".html"}:
        for pattern, replacement in TEXT_REPLACEMENTS:
            text = pattern.sub(replacement, text)
    if relative in {"docs/face-keys-release.md", "docs/runtime.md", "docs/technical-guide.md"}:
        # The source keeps a separately addressable candidate for internal
        # review.  Public Aoi has one canonical model, so scrub the candidate
        # name while retaining the surrounding procedure/history.
        text = text.replace("aoi_eye_fix", "aoi")
        text = text.replace("web/models/aoi_vowels", "web/models/aoi")
        text = text.replace("models/aoi_vowels", "models/aoi")
        text = text.replace("docs/CANDIDATES.md", "docs/publication.md")
        text = text.replace("recipes/aoi_rig.json", "recipes/aoi.json")
        text = text.replace("assets/aoi/vowels/manifest.json", "adopted vowel assets (omitted from public projection)")
        text = text.replace("assets/aoi/keyforms/", "discarded keyform art (omitted from public projection)/")
        text = text.replace("assets/aoi/original.png", "private original artwork (omitted from public projection)")
        text = text.replace("assets/aoi/", "private source artwork (omitted from public projection)/")
    if text != original:
        return text.encode("utf-8"), "public-redaction-v1"
    # Normalize text files to stable UTF-8/LF bytes even when the source was
    # checked out with Windows line endings.
    normalized = text.encode("utf-8")
    return normalized, "utf8-lf" if normalized != data else None


def add_entry(entries: dict[str, Entry], relative: str, source_path: str, data: bytes, transform: str | None = None) -> None:
    relative = clean_path(relative)
    if relative in entries:
        raise SyncError(f"duplicate projected path: {relative}")
    source_sha = hashlib.sha256(data).hexdigest()
    projected, automatic = transform_text(relative, data)
    transform = transform or automatic
    entries[relative] = Entry(relative, source_path, projected, source_sha, transform)


def project_entries(source: Path, source_ref: str | None) -> dict[str, Entry]:
    tracked = tracked_paths(source, source_ref)
    entries: dict[str, Entry] = {}
    candidates = {path for path in tracked if public_source_path(path)}
    # Explicitly include generated files that are intentionally allowed but
    # may still be untracked during the showcase worker's staging turn.
    for path in PUBLIC_EXTRAS:
        if path in tracked or (not source_ref and (source / Path(path)).is_file()):
            candidates.add(path)
    # Include only model.json and the atlas files it declares.  A rendered
    # rest_composite.png may exist as an ignored build preview, but it is
    # consumed by the source exporter and is intentionally not rediscovered
    # into the public tree.
    model_json = "web/models/aoi/model.json"
    if model_json in tracked or (not source_ref and (source / model_json).is_file()):
        candidates.add(model_json)
        try:
            model = json.loads(read_source(source, model_json, source_ref, tracked).decode("utf-8"))
            atlas_files = [item.get("file") for item in model.get("atlases", []) if isinstance(item, dict)]
        except (UnicodeDecodeError, ValueError, AttributeError) as exc:
            raise SyncError("adopted model.json is not valid JSON") from exc
        for atlas in atlas_files:
            if not isinstance(atlas, str) or "/" in atlas or "\\" in atlas or Path(atlas).name != atlas:
                raise SyncError(f"adopted model declares an unsafe atlas name: {atlas!r}")
            relative = f"web/models/aoi/{atlas}"
            if relative in tracked or (not source_ref and (source / relative).is_file()):
                candidates.add(relative)
    for relative in sorted(candidates):
        raw = read_source(source, relative, source_ref, tracked)
        add_entry(entries, relative, relative, raw)
    add_entry(entries, ".nojekyll", "generated:github-pages", b"", "generated-github-pages")
    return entries


def add_external_tree(entries: dict[str, Entry], root: Path, source_label: str, destination_prefix: str) -> dict[str, bytes]:
    root = ensure_directory(root, source_label)
    if not root.exists() or not root.is_dir():
        raise SyncError(f"{source_label} directory is missing: {root}")
    payload: dict[str, bytes] = {}
    for path in sorted(root.rglob("*")):
        if is_reparse(path):
            raise SyncError(f"{source_label} contains a symlink/junction: {path}")
        if not path.is_file():
            if path.is_symlink():
                raise SyncError(f"{source_label} contains a symlink: {path}")
            continue
        relative = clean_path(Path(destination_prefix) / path.relative_to(root))
        data = path.read_bytes()
        payload[relative] = data
        add_entry(entries, relative, f"{source_label}:{path.relative_to(root).as_posix()}", data)
    return payload


def add_external_file(entries: dict[str, Entry], path: Path, source_label: str, destination: str, data: bytes | None = None) -> None:
    reject_reparse_chain(path, source_label)
    if not path.exists() or not path.is_file() or is_reparse(path):
        raise SyncError(f"{source_label} is missing or unsafe: {path}")
    add_entry(entries, destination, source_label, path.read_bytes() if data is None else data)


def validate_model_package(path: Path, expected_commit: str, entries: dict[str, Entry]) -> tuple[dict, bytes, dict]:
    """Validate one immutable ZIP snapshot and match it to the public model."""
    reject_reparse_chain(path, "model package")
    if not path.exists() or not path.is_file():
        raise SyncError(f"model package is missing: {path}")
    raw = path.read_bytes()
    source = Path(__file__).resolve().parents[1]
    sys.path.insert(0, str(source))
    temporary: Path | None = None
    try:
        from seethrough_rig.package_validate import validate_package
        with tempfile.NamedTemporaryFile(prefix="sync-model-", suffix=".zip", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(raw)
        result = validate_package(temporary)
    except Exception as exc:  # validator supplies a precise error type/message
        raise SyncError(f"model package validation failed: {exc}") from exc
    finally:
        if temporary is not None:
            try:
                temporary.unlink()
            except FileNotFoundError:
                pass
    if not isinstance(result, dict) or result.get("valid") is not True:
        raise SyncError("model package validator did not return valid=true")
    package_manifest = result.get("manifest")
    provenance = package_manifest.get("provenance") if isinstance(package_manifest, dict) else None
    if not isinstance(provenance, dict) or provenance.get("commit") != expected_commit:
        raise SyncError("model package provenance.commit does not match --source-ref")
    canonical_model = entries.get("web/models/aoi/model.json")
    if canonical_model is None:
        raise SyncError("public projection has no canonical model.json")
    try:
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            if archive.read("model.json") != canonical_model.data:
                raise SyncError("model package model.json differs from projected canonical model")
            model = json.loads(canonical_model.data.decode("utf-8"))
            for atlas in model.get("atlases", []):
                name = atlas.get("file") if isinstance(atlas, dict) else None
                projected = entries.get(f"web/models/aoi/{name}") if isinstance(name, str) else None
                if projected is None or archive.read(name) != projected.data:
                    raise SyncError(f"model package atlas differs from projected canonical model: {name}")
    except SyncError:
        raise
    except (KeyError, json.JSONDecodeError, OSError, zipfile.BadZipFile) as exc:
        raise SyncError(f"model package snapshot cannot be inspected: {exc}") from exc
    return result, raw, provenance


def validate_runtime_package(payload: dict[str, bytes], expected_commit: str | None) -> dict:
    """Require a complete provenance inventory with no unlisted runtime files."""
    provenance_raw = payload.get("artifacts/runtime/runtime-provenance.json")
    if provenance_raw is None:
        raise SyncError("runtime package must contain runtime-provenance.json")
    try:
        provenance = json.loads(provenance_raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise SyncError("runtime provenance is not valid JSON") from exc
    if not isinstance(provenance, dict) or not re.fullmatch(r"[0-9a-f]{40}", str(provenance.get("source_head", ""))):
        raise SyncError("runtime provenance has no full source_head")
    if expected_commit is not None and provenance["source_head"] != expected_commit:
        raise SyncError("runtime package source_head does not match --source-ref")
    rows = provenance.get("files")
    if not isinstance(rows, list):
        raise SyncError("runtime provenance has no file inventory")
    listed: dict[str, dict] = {}
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get("path"), str):
            raise SyncError("runtime provenance has an invalid file row")
        relative = clean_path("artifacts/runtime/" + row["path"])
        if relative in listed or not isinstance(row.get("size"), int) or row["size"] < 0 or not re.fullmatch(r"[0-9a-f]{64}", str(row.get("sha256", ""))):
            raise SyncError("runtime provenance has duplicate or invalid file inventory")
        listed[relative] = row
    actual = set(payload) - {"artifacts/runtime/runtime-provenance.json"}
    if set(listed) != actual:
        raise SyncError("runtime package files do not exactly match runtime-provenance.json")
    for relative, row in listed.items():
        data = payload[relative]
        if len(data) != row["size"] or hashlib.sha256(data).hexdigest() != row["sha256"].lower():
            raise SyncError(f"runtime package hash/size mismatch: {relative}")
    return provenance


def manifest_integrity(manifest: dict) -> str:
    copy = dict(manifest)
    copy["manifest_sha256"] = ""
    payload = json.dumps(copy, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def load_previous(destination: Path) -> dict | None:
    path = destination / MANIFEST_NAME
    if not path.exists():
        return None
    if is_reparse(path) or not path.is_file():
        raise SyncError(f"public manifest is not a regular file: {path}")
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise SyncError(f"cannot read public manifest: {path}") from exc
    if not isinstance(manifest, dict) or manifest.get("schema_version") != 1:
        raise SyncError(f"unsupported public manifest: {path}")
    expected = manifest_integrity(manifest)
    if manifest.get("manifest_sha256") != expected:
        raise SyncError(f"public manifest integrity check failed: {path}")
    rows = manifest.get("files")
    if not isinstance(rows, list):
        raise SyncError("public manifest has no file inventory")
    previous: dict[str, str] = {}
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get("path"), str) or not re.fullmatch(r"[0-9a-f]{64}", str(row.get("sha256", ""))):
            raise SyncError("public manifest has an invalid file row")
        relative = clean_path(row["path"])
        if relative.casefold() == MANIFEST_NAME.casefold() or relative == ".git" or relative.startswith(".git/"):
            raise SyncError(f"public manifest contains a protected path: {relative}")
        if relative in previous:
            raise SyncError(f"public manifest has duplicate path: {relative}")
        previous[relative] = row["sha256"]
    return {"raw": manifest, "files": previous}


def destination_hash(root: Path, relative: str) -> str | None:
    target = reject_reparse_parents(root, relative)
    if not target.exists():
        return None
    if not target.is_file() or target.is_symlink():
        raise SyncError(f"destination managed target is not a regular file: {target}")
    digest = hashlib.sha256()
    with target.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def make_manifest(source: Path, commit: str, dirty: bool, worktree_dirty: bool, entries: dict[str, Entry], warnings: list[str], runtime_info: dict | None, model_info: dict | None) -> dict:
    rows = []
    for relative in sorted(entries):
        entry = entries[relative]
        row = {
            "path": relative,
            "source_path": entry.source_path,
            "size": len(entry.data),
            "sha256": entry.sha256,
            "source_sha256": entry.source_sha256,
        }
        if entry.transform:
            row["transform"] = entry.transform
        rows.append(row)
    manifest = {
        "schema_version": 1,
        "tool_version": TOOL_VERSION,
        "projection": PROJECTION_NAME,
        "source_commit": commit,
        "source_dirty": dirty,
        "source_worktree_dirty": worktree_dirty,
        "source_repository": "private source checkout (URL intentionally omitted)",
        "files": rows,
        "warnings": sorted(set(warnings)),
    }
    if runtime_info is not None:
        manifest["runtime_package"] = runtime_info
    if model_info is not None:
        manifest["model_package"] = model_info
    manifest["manifest_sha256"] = manifest_integrity(manifest)
    return manifest


def manifest_bytes(manifest: dict) -> bytes:
    return (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile(prefix=f".{path.name}.{uuid.uuid4().hex}.", suffix=".tmp", dir=path.parent, delete=False) as stream:
            temp_name = stream.name
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp_name, path)
    finally:
        if temp_name:
            try:
                Path(temp_name).unlink()
            except FileNotFoundError:
                pass


def plan_changes(destination: Path, previous: dict | None, entries: dict[str, Entry]) -> tuple[list[str], list[str]]:
    old = previous["files"] if previous else {}
    conflicts: list[str] = []
    operations: list[str] = []
    for relative, entry in sorted(entries.items()):
        current = destination_hash(destination, relative)
        if relative in old and current not in (None, old[relative]):
            conflicts.append(f"managed destination changed: {relative}")
        if relative not in old and current not in (None, entry.sha256):
            conflicts.append(f"unmanaged destination would be overwritten: {relative}")
        if current != entry.sha256:
            operations.append(f"write {relative}")
    for relative, old_hash in sorted(old.items()):
        if relative in entries:
            continue
        current = destination_hash(destination, relative)
        if current is None:
            continue
        if current != old_hash:
            conflicts.append(f"stale managed destination changed: {relative}")
        else:
            operations.append(f"delete {relative}")
    # PUBLIC-MANIFEST.json is tool metadata, but a hand edit is still a local
    # change.  If it is malformed load_previous already failed; if there is
    # no previous manifest it is an unmanaged file and we preserve it.
    if previous is not None:
        manifest_path = destination / MANIFEST_NAME
        if manifest_path.exists() and (is_reparse(manifest_path) or not manifest_path.is_file()):
            conflicts.append(f"public manifest is not a regular file: {manifest_path}")
    return operations, conflicts


def apply_changes(destination: Path, previous: dict | None, entries: dict[str, Entry], manifest: dict) -> None:
    old = previous["files"] if previous else {}
    for relative, entry in sorted(entries.items()):
        target = reject_reparse_parents(destination, relative)
        if target.exists() and target.is_dir():
            raise SyncError(f"destination target is a directory: {target}")
        atomic_write(target, entry.data)
    for relative in sorted(set(old) - set(entries)):
        target = reject_reparse_parents(destination, relative)
        if target.exists():
            target.unlink()
    atomic_write(destination / MANIFEST_NAME, manifest_bytes(manifest))


def build_entries(args: argparse.Namespace, source: Path, commit: str) -> tuple[dict[str, Entry], list[str], dict | None, dict | None]:
    entries = project_entries(source, args.source_ref)
    warnings: list[str] = []
    runtime_info: dict | None = None
    model_info: dict | None = None
    runtime = args.runtime_package
    if runtime is None:
        default_runtime = source / ".local" / "public-runtime"
        if default_runtime.is_dir():
            runtime = default_runtime
            warnings.append("using source .local/public-runtime; release runs should pass a clean source-ref package")
    if runtime is not None:
        runtime_payload = add_external_tree(entries, runtime, "runtime-package", "artifacts/runtime")
        provenance = validate_runtime_package(runtime_payload, commit)
        runtime_info = {"path": "artifacts/runtime", "file_count": len(runtime_payload) - 1, "provenance": provenance}
    else:
        warnings.append("runtime package not included; generate it from scripts/package_runtime.py for release")
    model_package = args.model_package
    if model_package is None:
        default_model = source / "artifacts" / "models" / "kotonoha-aoi.zip"
        if default_model.is_file():
            model_package = default_model
    if model_package is not None:
        checked, package_bytes, provenance = validate_model_package(model_package, commit, entries)
        add_external_file(entries, model_package, "validated-model-package", "artifacts/models/kotonoha-aoi.zip", package_bytes)
        model_info = {
            "path": "artifacts/models/kotonoha-aoi.zip",
            "sha256": hashlib.sha256(package_bytes).hexdigest(),
            "source_commit": provenance["commit"],
            "validation": "seethrough_rig.package_validate.validate_package",
            "capabilities": checked.get("capabilities", {}),
        }
    else:
        warnings.append("validated model ZIP not included; generate it after the final source commit")
    return entries, warnings, runtime_info, model_info


def synchronize(args: argparse.Namespace) -> dict:
    source = ensure_directory(Path(args.source), "source")
    destination = ensure_directory(Path(args.destination), "destination")
    if source == destination or source in destination.parents or destination in source.parents:
        raise SyncError("source and destination must not contain one another")
    requested_ref = args.source_ref
    commit = source_commit(source, requested_ref)
    # Resolve refs once.  Every Git read below must come from this immutable
    # full SHA, even when the caller supplied a moving branch name.
    if requested_ref is not None:
        args.source_ref = commit
    worktree_dirty = source_status(source)
    # With an immutable ref all projected tracked bytes come from Git even if
    # unrelated private work remains dirty in the source checkout.  The
    # initial working-tree projection records that it is provisional.
    dirty = worktree_dirty if args.source_ref is None else False
    entries, warnings, runtime_info, model_info = build_entries(args, source, commit)
    previous = load_previous(destination) if destination.exists() else None
    manifest_path = destination / MANIFEST_NAME
    if previous is None and manifest_path.exists():
        raise SyncError(f"existing unmanaged public manifest must be reviewed first: {manifest_path}")
    operations, conflicts = plan_changes(destination, previous, entries)
    if conflicts:
        raise SyncError("destination conflicts: " + "; ".join(conflicts))
    manifest = make_manifest(source, commit, dirty, worktree_dirty, entries, warnings, runtime_info, model_info)
    if args.dry_run:
        return {
            "ok": True,
            "dry_run": True,
            "source": str(source),
            "destination": str(destination),
            "source_commit": commit,
            "source_dirty": dirty,
            "source_worktree_dirty": worktree_dirty,
            "file_count": len(entries),
            "bytes": sum(len(entry.data) for entry in entries.values()),
            "operations": operations,
            "warnings": warnings,
            "manifest": manifest,
        }
    destination.mkdir(parents=True, exist_ok=True)
    apply_changes(destination, previous, entries, manifest)
    return {
        "ok": True,
        "dry_run": False,
        "source": str(source),
        "destination": str(destination),
        "source_commit": commit,
        "source_dirty": dirty,
        "source_worktree_dirty": worktree_dirty,
        "file_count": len(entries),
        "bytes": sum(len(entry.data) for entry in entries.values()),
        "operations": operations,
        "warnings": warnings,
        "manifest": str(destination / MANIFEST_NAME),
    }


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--destination", type=Path, default=DEFAULT_DESTINATION)
    parser.add_argument("--source-ref", help="immutable source commit/ref for a release projection")
    parser.add_argument("--runtime-package", type=Path, help="fresh output directory from package_runtime.py")
    parser.add_argument("--model-package", type=Path, help="validated data-only model ZIP")
    parser.add_argument("--dry-run", action="store_true", help="validate and print the plan without changing destination")
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    try:
        result = synchronize(parse_args(argv))
    except SyncError as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False))
        return 2
    except (OSError, ValueError, zipfile.BadZipFile) as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False))
        return 1
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
